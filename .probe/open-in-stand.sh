#!/bin/bash
# Дорога от алерта к редактору стенда.
#
# Панель зовёт `open`, а тот ведёт к редактору, который знает система, — то есть
# к рабочему профилю: папка стенда открылась бы новым окном не там, где идёт
# прогон. Алерту подсовывается этот скрипт (CFA_OPEN), и он говорит то же самое,
# но профилю стенда.
#
# Аргументы приходят такими, какими их дают `open`:
#   -b <bundle> <папка>   вывести вперёд окно этой папки
#   -b <bundle>           поднять само приложение
#   <ссылка>              отдать ссылку редактору
set -u
CODE="/Applications/Visual Studio Code.app/Contents/Resources/app/bin/code"
HERE="$(cd "$(dirname "$0")" && pwd)"
ARGS=(--user-data-dir="$HERE/vscode-user" --extensions-dir="$HERE/vscode-ext")

case "${1:-}" in
-b)
	# Без папки просить нечего: у стенда нет «просто поднять приложение», и
	# окно, которое вышло бы вперёд, было бы чужим.
	[ -n "${3:-}" ] || exit 0
	exec "$CODE" "${ARGS[@]}" "$3"
	;;
vscode://*)
	exec "$CODE" "${ARGS[@]}" --open-url "$1"
	;;
*)
	# Всё прочее — файл (лог, например): отдаётся редактору как есть.
	exec "$CODE" "${ARGS[@]}" "$1"
	;;
esac
